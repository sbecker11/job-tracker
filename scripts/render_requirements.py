#!/usr/bin/env python3
"""Render docs/REQUIREMENTS.md's numbered rules as a read-only HTML page.

    python scripts/render_requirements.py           # write docs/requirements.html
    python scripts/render_requirements.py --check   # exit 1 if it is out of date

The HTML is tracked in git and regenerated by `.githooks/pre-commit` whenever
REQUIREMENTS.md is committed; `tests/test_requirements_html.py` fails if the
two drift. Standard library only, so the hook runs without the venv. Output
carries no timestamp, so regenerating unchanged rules is a no-op.
"""

from __future__ import annotations

import argparse
import html
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE = REPO_ROOT / "docs" / "REQUIREMENTS.md"
OUTPUT = REPO_ROOT / "docs" / "requirements.html"

_RULE_ROW_RE = re.compile(r"^\|\s*([A-Z]+-\d+)\s*\|(.*)\|(.*)\|(.*)\|\s*$")
_SECTION_RE = re.compile(r"^##\s+(.+?)\s*$")
_TEST_FILE_RE = re.compile(r"\b(test_[\w]+\.py)\b")


@dataclass
class Rule:
    code: str
    text: str
    enforced: str
    status: str


@dataclass
class Section:
    title: str
    rules: list[Rule] = field(default_factory=list)


def parse(markdown: str) -> list[Section]:
    sections: list[Section] = []
    for line in markdown.splitlines():
        if m := _SECTION_RE.match(line):
            sections.append(Section(m.group(1)))
        elif (m := _RULE_ROW_RE.match(line)) and sections:
            code, text, enforced, status = (g.strip() for g in m.groups())
            sections[-1].rules.append(Rule(code, text, enforced, status))
    return [s for s in sections if s.rules]


def status_kind(status: str) -> str:
    word = re.sub(r"[*_`]", "", status).strip().split(" ", 1)[0].upper().rstrip(",.—-")
    return word if word in {"OK", "GAP", "BROKEN", "DECIDE", "RETIRED"} else "OTHER"


def inline(md: str) -> str:
    """Escape, then render `code`, **bold** and *italic*."""
    parts = re.split(r"(`[^`]*`)", md)
    out = []
    for part in parts:
        if part.startswith("`") and part.endswith("`") and len(part) >= 2:
            out.append(f"<code>{html.escape(part[1:-1])}</code>")
            continue
        s = html.escape(part)
        s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
        s = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", s)
        out.append(s)
    return "".join(out)


def enforced_html(enforced: str) -> str:
    s = inline(enforced)
    return _TEST_FILE_RE.sub(lambda m: f'<a href="../tests/{m.group(1)}">{m.group(1)}</a>', s)


