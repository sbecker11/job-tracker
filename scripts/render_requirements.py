_JS = """
const q = document.getElementById('q');
let kind = 'ALL';
function apply() {
  const needle = q.value.trim().toLowerCase();
  for (const row of document.querySelectorAll('tr.rule')) {
    const hit = (kind === 'ALL' || row.dataset.kind === kind) && (!needle || row.textContent.toLowerCase().includes(needle));
    row.classList.toggle('hidden', !hit);
  }
  for (const sec of document.querySelectorAll('section')) {
    sec.classList.toggle('hidden', !sec.querySelector('tr.rule:not(.hidden)'));
  }
}
q.addEventListener('input', apply);
for (const chip of document.querySelectorAll('.chip')) {
  chip.addEventListener('click', () => {
    kind = chip.dataset.kind;
    for (const c of document.querySelectorAll('.chip')) c.setAttribute('aria-pressed', String(c === chip));
    apply();
  });
}
"""


def render(markdown: str) -> str:
    sections = parse(markdown)
    rules = [r for s in sections for r in s.rules]
    counts: dict[str, int] = {}
    for r in rules:
        counts[status_kind(r.status)] = counts.get(status_kind(r.status), 0) + 1
    chips = [f'<button class="chip" data-kind="ALL" aria-pressed="true">All {len(rules)}</button>']
    for k in ("OK", "GAP", "BROKEN", "DECIDE", "RETIRED", "OTHER"):
        if counts.get(k):
            chips.append(f'<button class="chip" data-kind="{k}" aria-pressed="false">{k} {counts[k]}</button>')

    body = []
    for s in sections:
        anchor = re.sub(r"[^a-z0-9]+", "-", s.title.lower()).strip("-")
        rows = []
        for r in s.rules:
            k = status_kind(r.status)
            label = "" if k == "OTHER" else f'<span class="badge">{k}</span>'
            detail = r.status if k == "OTHER" else re.sub(rf"^\**{k}\**\s*(?:—\s*)?", "", r.status, flags=re.I)
            rows.append(
                f'<tr class="rule {k}" id="{r.code}" data-kind="{k}">'
                f'<td class="code"><a href="#{r.code}">{r.code}</a></td>'
                f"<td>{inline(r.text)}</td>"
                f'<td class="enforced">{enforced_html(r.enforced)}</td>'
                f'<td class="status">{label}{inline(detail)}</td></tr>'
            )
        body.append(
            f'<section id="{anchor}"><h2>{html.escape(s.title)}</h2>'
            "<table><thead><tr><th>ID</th><th>Rule</th><th>Enforced</th><th>Status</th></tr></thead>"
            f"<tbody>{''.join(rows)}</tbody></table></section>"
        )

    return (
        "<!DOCTYPE html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">"
        "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">"
        "<title>job-tracker requirements</title>"
        f"<style>{_CSS}</style></head><body>"
        "<!-- Generated from docs/REQUIREMENTS.md by scripts/render_requirements.py. Do not edit. -->"
        "<header><h1>job-tracker requirements</h1><div class=\"controls\">"
        '<input id="q" type="search" placeholder="Search rules, files, tests…">'
        f"{''.join(chips)}</div></header>"
        f"<main>{''.join(body)}</main>"
        f"<script>{_JS}</script></body></html>\n"
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/requirements.html is out of date")
    args = ap.parse_args(argv)
    expected = render(SOURCE.read_text(encoding="utf-8"))
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if args.check:
        if current != expected:
            print("docs/requirements.html is out of date — run scripts/render_requirements.py", file=sys.stderr)
            return 1
        return 0
    if current != expected:
        OUTPUT.write_text(expected, encoding="utf-8")
        print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
